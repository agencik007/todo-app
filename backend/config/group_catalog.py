"""
Starter group catalogue - single source of truth for onboarding and group suggestions.

Keywords exist only to improve text matching; they are never shown to users.
"""

from dataclasses import dataclass

from models.group import GroupColor


@dataclass(frozen=True)
class CatalogEntry:
    """A starter group the user can pick during onboarding."""

    key: str
    icon: str
    color: GroupColor
    name_pl: str
    name_en: str
    keywords_pl: tuple[str, ...]
    keywords_en: tuple[str, ...]
    preselected: bool = False

    def name(self, language: str) -> str:
        """Return the group name for the given language ("pl" or English fallback)."""
        return self.name_pl if language == "pl" else self.name_en

    def match_text(self) -> str:
        """Return both names and all keywords joined with ", " for matching."""
        return ", ".join(
            (self.name_pl, self.name_en, *self.keywords_pl, *self.keywords_en)
        )


