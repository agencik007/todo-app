"""
API Messages - Centralized message codes for API responses.
"""

from enum import Enum


class ApiMessages(str, Enum):
    """Enum containing all API message codes."""

    # Auth messages
    AUTH_EMAIL_ALREADY_REGISTERED = "AUTH_EMAIL_ALREADY_REGISTERED"
    AUTH_INVALID_JSON_BODY = "AUTH_INVALID_JSON_BODY"
    AUTH_INVALID_FORM_DATA = "AUTH_INVALID_FORM_DATA"
    AUTH_EMAIL_PASSWORD_REQUIRED = "AUTH_EMAIL_PASSWORD_REQUIRED"
    AUTH_INVALID_CREDENTIALS = "AUTH_INVALID_CREDENTIALS"
    AUTH_INACTIVE_USER = "AUTH_INACTIVE_USER"
    AUTH_EMAIL_NOT_VERIFIED = "AUTH_EMAIL_NOT_VERIFIED"
    AUTH_INVALID_REFRESH_TOKEN = "AUTH_INVALID_REFRESH_TOKEN"
    AUTH_INVALID_TOKEN_PAYLOAD = "AUTH_INVALID_TOKEN_PAYLOAD"
    AUTH_USER_NOT_FOUND_OR_INACTIVE = "AUTH_USER_NOT_FOUND_OR_INACTIVE"
    AUTH_PASSWORD_RESET_SENT = "AUTH_PASSWORD_RESET_SENT"
    AUTH_INVALID_RESET_TOKEN = "AUTH_INVALID_RESET_TOKEN"
    AUTH_PASSWORD_RESET_SUCCESS = "AUTH_PASSWORD_RESET_SUCCESS"
    AUTH_INVALID_VERIFICATION_TOKEN = "AUTH_INVALID_VERIFICATION_TOKEN"
    AUTH_EMAIL_VERIFIED_SUCCESS = "AUTH_EMAIL_VERIFIED_SUCCESS"
    AUTH_EMAIL_ALREADY_VERIFIED = "AUTH_EMAIL_ALREADY_VERIFIED"
    AUTH_VERIFICATION_EMAIL_SENT = "AUTH_VERIFICATION_EMAIL_SENT"
    AUTH_LOGOUT_SUCCESS = "AUTH_LOGOUT_SUCCESS"
    AUTH_LOGIN_SUCCESS = "AUTH_LOGIN_SUCCESS"
    AUTH_REGISTER_SUCCESS = "AUTH_REGISTER_SUCCESS"

    # Todo messages
    TODO_NOT_FOUND = "TODO_NOT_FOUND"
    TODO_NO_ACCESS = "TODO_NO_ACCESS"
    TODO_NO_UPDATE_PERMISSION = "TODO_NO_UPDATE_PERMISSION"
    TODO_NO_DELETE_PERMISSION = "TODO_NO_DELETE_PERMISSION"
    TODO_DELETED_SUCCESS = "TODO_DELETED_SUCCESS"
    TODO_REORDER_SUCCESS = "TODO_REORDER_SUCCESS"
    TODO_INVALID_INDEX = "TODO_INVALID_INDEX"

    # User messages
    USER_AVATAR_INVALID_TYPE = "USER_AVATAR_INVALID_TYPE"
    USER_AVATAR_TOO_LARGE = "USER_AVATAR_TOO_LARGE"
    USER_AVATAR_INVALID_EXTENSION = "USER_AVATAR_INVALID_EXTENSION"
    USER_AVATAR_SAVE_ERROR = "USER_AVATAR_SAVE_ERROR"
    USER_AVATAR_DELETED = "USER_AVATAR_DELETED"
    USER_LANGUAGE_UPDATED = "USER_LANGUAGE_UPDATED"


def api_error(code: ApiMessages) -> dict:
    """
    Create an error detail dict for HTTPException.

    Args:
        code: The API message code.

    Returns:
        dict: Error detail with messageCode.
    """
    return {"messageCode": code.value}


def api_success(code: ApiMessages, **extra) -> dict:
    """
    Create a success response dict.

    Args:
        code: The API message code.
        **extra: Additional fields to include in the response.

    Returns:
        dict: Success response with message and optional extra fields.
    """
    return {"message": code.value, **extra}
